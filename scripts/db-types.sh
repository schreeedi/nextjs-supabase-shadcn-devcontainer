#!/usr/bin/env bash
# Generate database types from the local Supabase → types/database.ts.
#
#   scripts/db-types.sh           rewrite the file
#   scripts/db-types.sh --check   exit 1 if the file differs from the schema
#
# Needs the local stack running (`npm run db:start`) with all migrations.
# Run after every new migration.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="types/database.ts"
# Inside the repo so Prettier picks up the project config.
TMP="types/.database.gen.ts"
trap 'rm -f "$TMP"' EXIT

{
  echo "// Generated by scripts/db-types.sh (supabase gen types) — do not edit."
  echo
  node_modules/.bin/supabase gen types typescript --local --schema public
} >"$TMP"
# --ignore-path: otherwise Prettier also reads .gitignore and skips the temp file.
node_modules/.bin/prettier --ignore-path /dev/null --write "$TMP" >/dev/null

if [ "${1:-}" = "--check" ]; then
  if ! diff -q "$TMP" "$OUT" >/dev/null 2>&1; then
    echo "types/database.ts differs from the local schema — run npm run db:types." >&2
    diff "$OUT" "$TMP" | head -40 >&2 || true
    exit 1
  fi
  echo "types/database.ts is up to date."
  exit 0
fi

cp "$TMP" "$OUT"
echo "written: $OUT"
